"""`xx-build` - set up this checkout's development environment, and switch its build mode.

Usage, from the repo root (bash; Git Bash on Windows):

    ./xx-build init [--mode MODE] [uv sync args...]          # fresh clone
    ./xx-build init --clean [--mode MODE] [uv sync args...]  # delete .venv and build/, then the same
    ./xx-build set-mode MODE [uv sync args...]               # switch build mode and rebuild
    ./xx-build rebuild [uv sync args...]                     # rebuild in the active mode
    ./xx-build show-mode                                     # active mode; fails if uv.toml is stale

After that, plain `uv sync` / `uv run` keep the environment current, in the active mode. `rebuild` is
`set-mode` with the active mode: for what plain `uv sync` does not redo in order (several C++ packages'
pyproject.toml or XX_CXX_SANITIZERS changed), to refresh the C++ packages' versions, or to finish a
switch that failed.

Build modes. `dev` (the default) is `[tool.uv]` in pyproject.toml as is: Debug, editable,
rebuild-on-import. Any other mode is a table under `[tool.dev_10x.modes]`; `set-mode` writes a
gitignored uv.toml = a copy of `[tool.uv]` (minus the fields uv only reads from pyproject.toml) with
that table merged in. uv then takes uv.toml instead of `[tool.uv]` (and says so on every command);
`set-mode dev` deletes it. uv.toml is a copy, so after editing `[tool.uv]` or the modes re-run
`set-mode` - `show-mode` tells when that is due.

`init` and `set-mode` sync in an order uv cannot express on its own:

1. the C++ build toolchain (the `build` dependency group, versions from uv.lock) goes in first: the
   in-tree C++ packages build without isolation, and uv does not install a no-isolation package's
   toolchain before building it;
2. py10x-kernel / py10x-infra next: py10x-fin-base-cxx's build needs an installed, importable kernel
   (stub generation on every OS, kernel's import library on Windows) - and must not import one that
   is being rebuilt at the same time;
3. then everything else (default dependency groups), py10x-fin-base-cxx included.

The C++ packages are always force-rebuilt (`--reinstall-package`): uv's cache may still hold wheels
that point at a deleted build/ dir or another mode's settings. Extra arguments (e.g. `--locked`,
`--no-group test`) are passed to the `uv sync` calls of steps 2 and 3.

`init` refuses to run when .venv or build/ already exists, so it never silently rebuilds over an
existing environment; `--clean` deletes both, but only after the mode is accepted. An unknown mode,
or a uv.toml xx-build did not write, leaves .venv and build/ in place. Without `--mode`, that
foreign file is refused before a venv is created.

Standard library only at import (it runs before the venv exists, via `./xx-build` ->
`uv run --no-project --isolated --with tomlkit -m dev_10x.xx_build`); tomlkit renders uv.toml. Its uv
calls are plain `uv`, looked up on PATH per call - not `$UV`, which with .venv activated points at
.venv's own copy that `--clean` deletes.
"""

from __future__ import annotations

import os
import re
import shutil
import stat
import subprocess
import sys
from pathlib import Path

ROOT = Path.cwd()
KERNEL_PACKAGES = ('py10x-kernel', 'py10x-infra')
DOWNSTREAM_CXX_PACKAGES = ('py10x-fin-base-cxx',)
DEFAULT_MODE = 'dev'
# [tool.uv] fields uv reads only from pyproject.toml (rejected in uv.toml): left out of the copy, and
# still taken from pyproject.toml.
PROJECT_ONLY_FIELDS = frozenset({'sources', 'workspace', 'default-groups', 'dev-dependencies', 'managed', 'package', 'conflicts'})
HEADER = (
    '# Generated by `./xx-build set-mode {mode}`: [tool.uv] from pyproject.toml + [tool.dev_10x.modes.{mode}].\n'
    '# Do not edit - change pyproject.toml and re-run set-mode; `./xx-build set-mode dev` deletes this file.\n'
)
HEADER_MODE = re.compile(r'^# Generated by `\./xx-build set-mode ([\w.-]+)`')
# The mode the venv was last fully synced in (`<mode> incomplete` while a sync runs), so show-mode can
# tell an interrupted switch from a finished one.
SYNCED_MODE = Path('.venv') / 'xx-build-mode'
USAGE = 'Usage: ./xx-build init [--clean] [--mode MODE] [uv sync args...] | set-mode MODE [uv sync args...] | rebuild [uv sync args...] | show-mode'
# show-mode prints this and env_check.default_mode raises it: active_mode() is None, not dev.
FOREIGN_MODE_MESSAGE = 'build mode: custom (uv.toml was not written by xx-build)'


def _reinstall(names: tuple[str, ...]) -> list[str]:
    return [arg for name in names for arg in ('--reinstall-package', name)]


def _rmtree(path: Path) -> None:
    """`shutil.rmtree` that also removes read-only files: on Windows it cannot delete the read-only git
    pack files CMake FetchContent leaves under build/.../_deps/*/.git."""

    def make_writable_and_retry(func, p, _exc):
        os.chmod(p, stat.S_IWRITE)
        func(p)

    if sys.version_info >= (3, 12):
        shutil.rmtree(path, onexc=make_writable_and_retry)
    else:
        shutil.rmtree(path, onerror=make_writable_and_retry)


def _uv_env() -> dict[str, str]:
    """The environment for the inner uv calls, minus the VIRTUAL_ENV of `./xx-build`'s own isolated
    `uv run` environment (uv would warn on every call that it does not match the project's .venv)."""
    return {k: v for k, v in os.environ.items() if k != 'VIRTUAL_ENV'}


# ---------------------------------------------------------------------------------- build modes


def _modes(root: Path) -> dict:
    import tomllib

    tool = tomllib.loads((root / 'pyproject.toml').read_text(encoding='utf-8')).get('tool', {})
    return tool.get('dev_10x', {}).get('modes', {})


def mode_names(root: Path = ROOT) -> list[str]:
    return [DEFAULT_MODE, *_modes(root)]


def _merge(base: dict, overrides: dict) -> dict:
    for key, value in overrides.items():
        if isinstance(value, dict) and isinstance(base.get(key), dict):
            _merge(base[key], value)
        else:
            base[key] = value
    return base


def render(mode: str, root: Path = ROOT) -> str:
    """The uv.toml for a non-default mode."""
    import tomlkit

    tool = tomlkit.parse((root / 'pyproject.toml').read_text(encoding='utf-8')).unwrap().get('tool', {})
    modes = tool.get('dev_10x', {}).get('modes', {})
    if mode not in modes:
        raise ValueError(f'unknown build mode {mode!r} - one of: {", ".join(mode_names(root))}')
    settings = {k: v for k, v in tool.get('uv', {}).items() if k not in PROJECT_ONLY_FIELDS}
    return HEADER.format(mode=mode) + tomlkit.dumps(_merge(settings, modes[mode]))


def active_mode(root: Path = ROOT) -> str | None:
    """The mode uv.toml was generated for, `dev` without one, None for a uv.toml xx-build did not write."""
    uv_toml = root / 'uv.toml'
    if not uv_toml.exists():
        return DEFAULT_MODE
    match = HEADER_MODE.match(uv_toml.read_text(encoding='utf-8'))
    return match.group(1) if match else None


def _refuse_foreign_uv_toml(root: Path) -> None:
    """A uv.toml xx-build did not write is not a build mode and must not be overwritten."""
    if active_mode(root) is None:
        raise ValueError(f'{root / "uv.toml"} was not written by xx-build - move it away first')


def write_mode(mode: str, root: Path = ROOT) -> None:
    """Write (or, for `dev`, delete) uv.toml. Refuses to touch a uv.toml xx-build did not write."""
    uv_toml = root / 'uv.toml'
    _refuse_foreign_uv_toml(root)
    if mode == DEFAULT_MODE:
        uv_toml.unlink(missing_ok=True)
    else:
        uv_toml.write_text(render(mode, root), encoding='utf-8')


def show_mode(root: Path = ROOT) -> int:
    mode = active_mode(root)
    if mode is None:
        print(FOREIGN_MODE_MESSAGE)
        return 1
    print(f'build mode: {mode}  (modes: {", ".join(mode_names(root))})')
    if mode != DEFAULT_MODE:
        try:
            current = render(mode, root)
        except ValueError as exc:
            print(f'xx-build: {exc}', file=sys.stderr)
            return 1
        if (root / 'uv.toml').read_text(encoding='utf-8') != current:
            print('xx-build: uv.toml is out of date with pyproject.toml - run `./xx-build rebuild`.', file=sys.stderr)
            return 1
    synced = root / SYNCED_MODE
    if synced.is_file() and synced.read_text(encoding='utf-8').strip() != mode:
        print(
            f'xx-build: the venv is not fully in build mode {mode} (the last switch did not finish) - run `./xx-build rebuild`.',
            file=sys.stderr,
        )
        return 1
    return 0


# --------------------------------------------------------------------------------- init / sync


def sync_commands(sync_args: list[str]) -> list[list[str]]:
    """The ordered uv sync calls `init` and `set-mode` run (see the module docstring)."""
    # Steps 1-2 --inexact: add/rebuild what they need and leave the rest installed (an exact partial sync
    # would first uninstall everything else - a near-empty venv if a switch is interrupted). Step 3 is exact.
    return [
        ['uv', 'sync', '--inexact', '--frozen', '--only-group', 'build'],
        ['uv', 'sync', '--inexact', '--no-default-groups', '--group', 'build', *_reinstall(KERNEL_PACKAGES), *sync_args],
        ['uv', 'sync', *_reinstall(DOWNSTREAM_CXX_PACKAGES), *sync_args],
    ]


def init_commands(sync_args: list[str]) -> list[list[str]]:
    """The uv calls `init` runs, in order."""
    return [['uv', 'venv'], *sync_commands(sync_args)]


def _run(commands: list[list[str]], root: Path) -> int:
    env = _uv_env()
    for cmd in commands:
        print('$', ' '.join(cmd), flush=True)
        result = subprocess.run(cmd, cwd=root, env=env, check=False)
        if result.returncode:
            return result.returncode
    return 0


def _sync_in_mode(commands: list[list[str]], root: Path) -> int:
    """Run the sync commands, recording in .venv whether the venv ended up fully in the active mode."""
    mode = active_mode(root)
    synced = root / SYNCED_MODE

    def record(text: str) -> None:
        if synced.parent.is_dir():
            synced.write_text(text + '\n', encoding='utf-8')

    record(f'{mode} incomplete')
    rc = _run(commands, root)
    if rc:
        print(
            f'xx-build: the sync failed, so the venv is not fully in build mode {mode} - fix the cause (on Windows: a '
            f'process still using the venv) and run `./xx-build rebuild`.',
            file=sys.stderr,
        )
        return rc
    record(mode)
    return 0


def init(clean: bool, sync_args: list[str], root: Path = ROOT, mode: str | None = None) -> int:
    existing = [p for p in (root / '.venv', root / 'build') if p.exists()]
    if existing and not clean:
        names = ' and '.join(p.name + '/' for p in existing)
        print(f'xx-build init: {names} already exist - run `./xx-build init --clean` to delete them and start over.', file=sys.stderr)
        return 1
    # ValueError here (unknown mode, foreign uv.toml) must leave .venv and build/ in place.
    if mode is not None:
        write_mode(mode, root)
    else:
        _refuse_foreign_uv_toml(root)
    for path in existing:
        print(f'xx-build init: removing {path.name}/', flush=True)
        _rmtree(path)
    print(f'xx-build init: build mode {active_mode(root)}', flush=True)
    rc = _run(init_commands(sync_args)[:1], root)  # uv venv
    return rc or _sync_in_mode(sync_commands(sync_args), root)


def set_mode(mode: str, sync_args: list[str], root: Path = ROOT) -> int:
    write_mode(mode, root)
    print(f'xx-build set-mode: build mode {mode}', flush=True)
    if not (root / '.venv').exists():
        print('xx-build set-mode: no .venv yet - run `./xx-build init` to build in this mode.', flush=True)
        return 0
    return _sync_in_mode(sync_commands(sync_args), root)


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if not args or args[0] in ('-h', '--help'):
        print(__doc__)
        return 0 if args else 2
    command, rest = args[0], args[1:]
    try:
        if command == 'show-mode' and not rest:
            return show_mode()
        if command == 'set-mode' and rest and not rest[0].startswith('-'):
            return set_mode(rest[0], rest[1:])
        if command == 'rebuild':
            mode = active_mode()
            if mode is None:
                raise ValueError('uv.toml was not written by xx-build - run `./xx-build set-mode MODE`')
            return set_mode(mode, rest)
        if command == 'init':
            mode = None
            if '--mode' in rest:
                i = rest.index('--mode')
                if i + 1 >= len(rest):
                    raise ValueError('--mode needs a value')
                mode = rest[i + 1]
                rest = rest[:i] + rest[i + 2 :]
            return init('--clean' in rest, [a for a in rest if a != '--clean'], mode=mode)
    except ValueError as exc:
        print(f'xx-build: {exc}', file=sys.stderr)
        return 2
    print(USAGE, file=sys.stderr)
    return 2


if __name__ == '__main__':
    sys.exit(main())
